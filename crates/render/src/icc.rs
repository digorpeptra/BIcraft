//! The sRGB ICC profile of a PDF/A file's output intent (`pdf.rs`), built here from the sRGB
//! colour space's published parameters (IEC 61966-2-1: the primaries and the D65 white point
//! adapted to the profile connection space's D50 white with the Bradford transform, and the
//! transfer curve), so no profile file from elsewhere is embedded.
//!
//! The layout is the ICC's version 2 format (ICC.1:2001-04): a 128-byte header, the tag table,
//! then the tags: the description and copyright texts, the media white point, the three
//! colorants and one 1024-entry tone curve shared by the three channels.

/// A number as `s15Fixed16Number`.
fn s15(v: f64) -> [u8; 4] {
    ((v * 65536.0).round() as i32).to_be_bytes()
}

/// The PCS illuminant, D50, as the ICC writes it.
const D50: [[u8; 4]; 3] = [
    0x0000_F6D6u32.to_be_bytes(),
    0x0001_0000u32.to_be_bytes(),
    0x0000_D32Du32.to_be_bytes(),
];

/// The sRGB primaries' XYZ (D50-adapted) for red, green and blue.
const COLORANTS: [[f64; 3]; 3] = [
    [0.436_074_7, 0.222_504_5, 0.013_932_2],
    [0.385_064_9, 0.716_878_6, 0.097_104_5],
    [0.143_080_4, 0.060_616_9, 0.714_173_3],
];

/// The profile's name.
pub(crate) const SRGB_NAME: &str = "sRGB IEC61966-2.1";

fn xyz(v: [[u8; 4]; 3]) -> Vec<u8> {
    let mut b = b"XYZ \0\0\0\0".to_vec();
    for x in v {
        b.extend_from_slice(&x);
    }
    b
}

/// The sRGB transfer curve (encoded value to linear light), sampled at 1024 points.
fn curve() -> Vec<u8> {
    const N: u32 = 1024;
    let mut b = b"curv\0\0\0\0".to_vec();
    b.extend_from_slice(&N.to_be_bytes());
    for i in 0..N {
        let x = f64::from(i) / f64::from(N - 1);
        let y = if x <= 0.040_45 {
            x / 12.92
        } else {
            ((x + 0.055) / 1.055).powf(2.4)
        };
        b.extend_from_slice(&((y.clamp(0.0, 1.0) * 65535.0).round() as u16).to_be_bytes());
    }
    b
}

fn desc(s: &str) -> Vec<u8> {
    let mut b = b"desc\0\0\0\0".to_vec();
    b.extend_from_slice(&(s.len() as u32 + 1).to_be_bytes());
    b.extend_from_slice(s.as_bytes());
    b.push(0);
    // no Unicode or ScriptCode description
    b.extend_from_slice(&[0u8; 4 + 4 + 2 + 1 + 67]);
    b
}

fn text(s: &str) -> Vec<u8> {
    let mut b = b"text\0\0\0\0".to_vec();
    b.extend_from_slice(s.as_bytes());
    b.push(0);
    b
}

/// The sRGB display profile (ICC version 2.1, class `mntr`, data `RGB `, PCS `XYZ `).
pub(crate) fn srgb_profile() -> Vec<u8> {
    let colorant = |i: usize| {
        let c = COLORANTS.get(i).copied().unwrap_or([0.0; 3]);
        xyz([s15(c[0]), s15(c[1]), s15(c[2])])
    };
    let trc = curve();
    // (signature, data); the three tone curves share one copy
    let tags: Vec<(&[u8; 4], Vec<u8>)> = vec![
        (b"desc", desc(SRGB_NAME)),
        (
            b"cprt",
            text("Generated by BIcraft from the sRGB parameters of IEC 61966-2-1"),
        ),
        (b"wtpt", xyz(D50)),
        (b"rXYZ", colorant(0)),
        (b"gXYZ", colorant(1)),
        (b"bXYZ", colorant(2)),
        (b"rTRC", trc),
    ];
    let shared: [&[u8; 4]; 2] = [b"gTRC", b"bTRC"];
    let count = tags.len() + shared.len();
    let mut table: Vec<u8> = Vec::new();
    let mut data: Vec<u8> = Vec::new();
    let base = 128 + 4 + count * 12;
    let mut trc_at = (0usize, 0usize);
    for (sig, body) in &tags {
        let at = base + data.len();
        table.extend_from_slice(*sig);
        table.extend_from_slice(&(at as u32).to_be_bytes());
        table.extend_from_slice(&(body.len() as u32).to_be_bytes());
        if *sig == b"rTRC" {
            trc_at = (at, body.len());
        }
        data.extend_from_slice(body);
        while !data.len().is_multiple_of(4) {
            data.push(0);
        }
    }
    for sig in shared {
        table.extend_from_slice(sig);
        table.extend_from_slice(&(trc_at.0 as u32).to_be_bytes());
        table.extend_from_slice(&(trc_at.1 as u32).to_be_bytes());
    }
    let size = base + data.len();
    let mut h = vec![0u8; 128];
    let mut put = |at: usize, b: &[u8]| {
        if let Some(s) = h.get_mut(at..at + b.len()) {
            s.copy_from_slice(b);
        }
    };
    put(0, &(size as u32).to_be_bytes());
    put(8, &0x0210_0000u32.to_be_bytes());
    put(12, b"mntr");
    put(16, b"RGB ");
    put(20, b"XYZ ");
    // a fixed creation date: the output stays deterministic
    for (i, v) in [2026u16, 11, 27, 0, 0, 0].iter().enumerate() {
        put(24 + i * 2, &v.to_be_bytes());
    }
    put(36, b"acsp");
    for (i, v) in D50.iter().enumerate() {
        put(68 + i * 4, v);
    }
    let mut out = h;
    out.extend_from_slice(&(count as u32).to_be_bytes());
    out.extend_from_slice(&table);
    out.extend_from_slice(&data);
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn u32_at(b: &[u8], at: usize) -> u32 {
        u32::from_be_bytes(b[at..at + 4].try_into().unwrap())
    }

    fn fixed(b: &[u8], at: usize) -> f64 {
        f64::from(u32_at(b, at) as i32) / 65536.0
    }

    #[test]
    fn the_srgb_profile_reads_as_a_v2_display_profile() {
        let p = srgb_profile();
        assert_eq!(u32_at(&p, 0) as usize, p.len());
        assert_eq!(&p[36..40], b"acsp");
        assert_eq!(
            (&p[12..16], &p[16..20], &p[20..24]),
            (&b"mntr"[..], &b"RGB "[..], &b"XYZ "[..])
        );
        assert_eq!(p[8], 2, "major version");
        // every tag lies inside the profile; the required ones are there
        let n = u32_at(&p, 128) as usize;
        let mut sigs = Vec::new();
        for i in 0..n {
            let r = 132 + i * 12;
            let (at, len) = (u32_at(&p, r + 4) as usize, u32_at(&p, r + 8) as usize);
            assert!(at + len <= p.len() && at % 4 == 0);
            sigs.push((p[r..r + 4].to_vec(), at));
        }
        for want in [
            b"desc", b"cprt", b"wtpt", b"rXYZ", b"gXYZ", b"bXYZ", b"rTRC", b"gTRC", b"bTRC",
        ] {
            assert!(
                sigs.iter().any(|(s, _)| s == want),
                "{}",
                String::from_utf8_lossy(want)
            );
        }
        // the colorants add up to the D50 white (what a matrix profile maps white to)
        let at = |sig: &[u8]| sigs.iter().find(|(s, _)| s == sig).unwrap().1;
        for k in 0..3 {
            let sum: f64 = [b"rXYZ", b"gXYZ", b"bXYZ"]
                .iter()
                .map(|s| fixed(&p, at(&s[..]) + 8 + k * 4))
                .sum();
            let white = fixed(&p, 68 + k * 4);
            assert!((sum - white).abs() < 0.001, "{k}: {sum} vs {white}");
        }
        // the tone curve rises from black to white
        let c = at(b"rTRC");
        let count = u32_at(&p, c + 8) as usize;
        let vals: Vec<u16> = (0..count)
            .map(|i| u16::from_be_bytes([p[c + 12 + i * 2], p[c + 13 + i * 2]]))
            .collect();
        assert_eq!((vals[0], *vals.last().unwrap()), (0, 65535));
        assert!(vals.windows(2).all(|w| w[0] <= w[1]));
        // mid grey is darker than half in linear light (the sRGB curve, not a straight line)
        assert!(vals[count / 2] < 65535 / 3, "{}", vals[count / 2]);
    }
}
