/// The columns of an INFO function BIcraft knows (any case); `None` for the others.
pub fn info_columns(name: &str) -> Option<&'static [(&'static str, InfoType)]> {
    let up = name.to_ascii_uppercase();
    Some(match up.as_str() {
        "INFO.TABLES" => TABLES,
        "INFO.PARTITIONS" => PARTITIONS,
        "INFO.MODEL" => MODEL,
        "INFO.COLUMNS" => COLUMNS,
        "INFO.MEASURES" => MEASURES,
        "INFO.RELATIONSHIPS" => RELATIONSHIPS,
        "INFO.VIEW.TABLES" => VIEW_TABLES,
        "INFO.VIEW.COLUMNS" => VIEW_COLUMNS,
        "INFO.VIEW.MEASURES" => VIEW_MEASURES,
        "INFO.VIEW.RELATIONSHIPS" => VIEW_RELATIONSHIPS,
        _ => return None,
    })
}
