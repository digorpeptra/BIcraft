/// Reserved words that may still be a bare (unquoted) table reference: `COUNTROWS(Date)` and
/// `EVALUATE Values` are fine, `Date[Year]` is not. Upper-case, sorted.
const BARE_TABLE_OK: &[&str] = &[
    "BOOLEAN", "CHAPTERS", "COLUMNS", "DATE", "DOUBLE", "LOG", "LONG", "ROWS", "TEXT", "VALUES",
];

/// Words that only cannot name a variable, function or parameter: `Densify[x]` and
/// `DEFINE TABLE Densify = …` are fine. Upper-case, sorted.
const NAME_ONLY: &[&str] = &["DENSIFY", "ROWPAGES"];

fn contains(list: &[&str], word: &str) -> bool {
    list.binary_search_by(|r| r.bytes().cmp(word.bytes().map(|b| b.to_ascii_uppercase())))
        .is_ok()
}

/// Whether `word` is reserved (ASCII case-insensitive): it cannot qualify a column or name a
/// table without quotes, nor name a variable.
pub(crate) fn is_reserved(word: &str) -> bool {
    contains(RESERVED, word)
}

/// Whether `word` cannot name a variable, user-defined function or function parameter.
pub(crate) fn is_reserved_name(word: &str) -> bool {
    is_reserved(word) || contains(NAME_ONLY, word)
}

/// Whether an unquoted `word` cannot be a bare table reference (`COUNTROWS(word)`).
pub(crate) fn is_reserved_bare(word: &str) -> bool {
    is_reserved(word) && !contains(BARE_TABLE_OK, word)
}

/// Whether a table name must be quoted when written in DAX: `Sales` stays bare, `Order Lines`,
/// `Typed` or `Date` become `'Order Lines'`, `'Typed'`, `'Date'`.
pub fn table_needs_quotes(name: &str) -> bool {
    let mut chars = name.chars();
    let simple = chars.next().is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_');
    !simple || is_reserved(name) || name.eq_ignore_ascii_case("TRUE") || name.eq_ignore_ascii_case("FALSE")
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn lists_are_sorted_upper_case_and_searchable() {
        for list in [RESERVED, BARE_TABLE_OK, NAME_ONLY] {
            assert!(list.windows(2).all(|w| w[0] < w[1]));
            assert!(list.iter().all(|w| w.bytes().all(|b| !b.is_ascii_lowercase())));
        }
        assert!(BARE_TABLE_OK.iter().all(|w| is_reserved(w)));
        assert!(NAME_ONLY.iter().all(|w| !is_reserved(w)));
        for w in [
            "date",
            "Value",
            "SUM",
            "rank",
            "Filter",
            "TEXT",
            "asc",
            "rollup",
            "Typed",
            "typed",
            "Type",
            "Status",
            "Name",
            "Key",
            "ID",
            "Version",
            "Description",
            "Binary",
            "Visual",
        ] {
            assert!(is_reserved(w), "{w}");
            assert!(is_reserved_name(w), "{w}");
        }
        for w in [
            "Year", "Index", "Total", "Calendar", "Window", "Product", "Currency", "Day", "", "Function",
            "Val", "Expr", "Scalar", "AnyVal", "AnyRef", "Int64", "Decimal", "String", "DateTime", "Variant",
            "Numeric", "Sales", "Densify",
        ] {
            assert!(!is_reserved(w), "{w}");
        }
        assert!(is_reserved_name("densify") && is_reserved_name("RowPages"));
        assert!(is_reserved_bare("Typed") && is_reserved_bare("Status"));
        assert!(!is_reserved_bare("Date") && !is_reserved_bare("Values") && !is_reserved_bare("Sales"));
    }

    #[test]
    fn table_quoting() {
        for (name, quoted) in [
            ("Sales", false),
            ("_x1", false),
            ("Typed", true),
            ("Date", true),
            ("Order Lines", true),
            ("1st", true),
            ("true", true),
            ("", true),
            ("Café", true),
        ] {
            assert_eq!(table_needs_quotes(name), quoted, "{name}");
        }
    }
}
