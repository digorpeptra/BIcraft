//! Words the DAX engine reserves. An unquoted reserved word cannot be:
//! - a table qualifier: `Date[Year]` is a syntax error, `'Date'[Year]` is fine;
//! - a table name in a query definition: `DEFINE TABLE Typed = …`, `DEFINE MEASURE Typed[m] = …`;
//! - a variable, user-defined function or function parameter name: `VAR Value = 1`.
//!
//! Most of them cannot be a bare table reference either (`COUNTROWS(Typed)`, `EVALUATE Status`);
//! the few that can are in [`BARE_TABLE_OK`]. Column and measure names are always bracketed and
//! never clash.
//!
//! The engine also refuses many MDX and DMX keywords, so the list holds the older DAX
//! functions (`SUM`, `FILTER`, `DATE`…), the query keywords (`DEFINE`, `ORDER`, `START`…) and many
//! MDX/DMX words that are common table names (`Name`, `Status`, `Key`, `Type`, `Typed`, `Version`,
//! `Description`…). Found by probing Power BI Desktop 2.158.1304.0's engine (Analysis Services
//! 17.0.87.18), see `docs/formats/dax-functions.md` §"Reserved words" and `docs/dax-oracle.md`.
//! Newer DAX functions (`INDEX`, `WINDOW`, `CALENDAR`, `YEAR`…) and the user-defined-function
//! type words (`VAL`, `EXPR`, `SCALAR`, `ANYVAL`, `INT64`…) are not reserved.

